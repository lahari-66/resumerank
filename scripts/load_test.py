"""Burst-load test: shows the queue absorbing a spike and Lambda scaling out.

    python scripts/load_test.py            # 40 uploads, 20 at a time
    python scripts/load_test.py 60 30      # 60 uploads, 30 at a time

Reads API_BASE_URL and RECRUITER_KEY from .env. Creates a fresh job, fires the uploads through
the real API (pre-signed URL + PUT to S3, exactly like the browser), then polls until every
resume is scored and prints throughput and latency. Standard library only.

While it runs, watch the CloudWatch dashboard: Lambda ConcurrentExecutions rises, the SQS queue
depth spikes then drains, and API Gateway may answer some requests with 429 (throttling), which
this script retries.
"""

import json
import os
import statistics
import sys
import threading
import time
import urllib.error
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESUMES = ["R1", "R2", "R4", "R5", "R6", "R7", "R8"]   # text PDFs (R3 needs OCR)


def load_env():
    env = {}
    path = os.path.join(ROOT, ".env")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    env.update({k: v for k, v in os.environ.items() if k in ("API_BASE_URL", "RECRUITER_KEY")})
    return env


ENV = load_env()
API = ENV.get("API_BASE_URL", "").rstrip("/")
KEY = ENV.get("RECRUITER_KEY", "")
throttled = 0
lock = threading.Lock()


def request(method, url, body=None, headers=None, raw=None):
    """JSON request with retry on 429 (API Gateway throttling) and 5xx."""
    global throttled
    headers = dict(headers or {})
    data = raw
    if body is not None:
        data = json.dumps(body).encode()
        headers["Content-Type"] = "application/json"
    for attempt in range(8):
        req = urllib.request.Request(url, data=data, method=method, headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=30) as res:
                text = res.read().decode() or "{}"
                return json.loads(text) if text.startswith("{") else {}
        except urllib.error.HTTPError as e:
            if e.code == 429 or e.code >= 500:
                if e.code == 429:
                    with lock:
                        throttled += 1
                time.sleep(min(0.25 * 2 ** attempt, 4))
                continue
            raise RuntimeError(f"{method} {url.split('?')[0]} -> {e.code}: {e.read().decode()[:200]}")
    raise RuntimeError(f"{method} {url.split('?')[0]} kept failing")


def api(method, path, body=None, recruiter=False):
    headers = {"x-recruiter-key": KEY} if recruiter and KEY else {}
    return request(method, API + path, body, headers)


def upload(job_id, i):
    rid = RESUMES[i % len(RESUMES)]
    with open(os.path.join(ROOT, "tests", "resumes", f"{rid}.pdf"), "rb") as f:
        pdf = f.read()
    started = time.time()
    signed = api("POST", "/upload-url", {"jobId": job_id, "name": f"Load test {i + 1:03d} ({rid})",
                                         "contentType": "application/pdf", "fileSize": len(pdf)})
    request("PUT", signed["uploadUrl"], headers=signed["headers"], raw=pdf)
    return time.time() - started


def iso(ts):
    return datetime.strptime(ts, "%Y-%m-%dT%H:%M:%SZ")


def pct(values, p):
    values = sorted(values)
    return values[min(len(values) - 1, int(round(p / 100 * (len(values) - 1))))]


def main():
    total = int(sys.argv[1]) if len(sys.argv) > 1 else 40
    parallel = int(sys.argv[2]) if len(sys.argv) > 2 else 20
    if not API:
        sys.exit("set API_BASE_URL in .env")

    job = api("POST", "/jobs", {"title": f"Load test {datetime.now():%H:%M}", "minYears": 2,
                                "requiredSkills": ["python", "aws", "docker", "linux", "sql"],
                                "recruiterEmail": "loadtest@example.com",
                                "description": "Generated by scripts/load_test.py"}, recruiter=True)
    job_id = job["jobId"]
    print(f"job {job_id}\nuploading {total} resumes, {parallel} at a time…")

    t0 = time.time()
    with ThreadPoolExecutor(max_workers=parallel) as pool:
        latencies = list(pool.map(lambda i: upload(job_id, i), range(total)))
    upload_secs = time.time() - t0
    print(f"uploads done in {upload_secs:.1f} s  ({total / upload_secs:.1f} uploads/s)  "
          f"upload latency p50 {pct(latencies, 50):.2f} s, p95 {pct(latencies, 95):.2f} s, "
          f"429 throttled responses retried: {throttled}")

    deadline = time.time() + 300
    while True:
        data = api("GET", f"/candidates?jobId={job_id}", recruiter=True)
        counts = {}
        for c in data["candidates"]:
            counts[c["status"]] = counts.get(c["status"], 0) + 1
        print(f"  t+{time.time() - t0:5.1f} s  {counts}")
        if counts.get("PENDING", 0) == 0 or time.time() > deadline:
            break
        time.sleep(3)
    all_secs = time.time() - t0

    done = [c for c in data["candidates"] if c["status"] == "SCORED"]
    lag = [(iso(c["processedAt"]) - iso(c["createdAt"])).total_seconds()
           for c in done if c.get("processedAt") and c.get("createdAt")]
    print("\n=== result ===")
    print(f"resumes: {total}  scored: {len(done)}  statuses: {counts}")
    print(f"end-to-end: {all_secs:.1f} s for the whole burst  ({len(done) / all_secs:.2f} resumes/s)")
    if lag:
        print(f"per-resume upload->scored: p50 {pct(lag, 50):.0f} s, p95 {pct(lag, 95):.0f} s, max {max(lag):.0f} s")
    if done:
        print(f"scores: min {min(c['score'] for c in done)}, mean {statistics.mean(c['score'] for c in done):.1f}, "
              f"max {max(c['score'] for c in done)}")
    print("\nNow open CloudWatch -> Dashboards -> ResumeRank (last 15 minutes) and screenshot:\n"
          "  Lambda concurrent executions, SQS queue depth, API Gateway requests/429s.")
    print(f"Recruiter view: recruiter.html?jobId={job_id}")


if __name__ == "__main__":
    main()
